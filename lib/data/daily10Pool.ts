/**
 * Returns exactly 10 distinct quality words for a given calendar date string (YYYY-MM-DD).
 * Deterministically rotates through the vocabulary pool based on the date seed.
 * Guarantees no duplicates and exactly 10 words.
 */
export function getDaily10WordsForDate(dateString: string): DailyWord[] {
  const seed = getDateSeed(dateString)
  const total = DAILY_VOCABULARY_POOL.length
  
  // Calculate starting index from seed
  const startIndex = (seed * 7) % total
  const selected: DailyWord[] = []
  const usedIds = new Set<string>()

  let offset = 0
  while (selected.length < 10 && offset < total * 2) {
    const word = DAILY_VOCABULARY_POOL[(startIndex + offset) % total]
    if (!usedIds.has(word.id)) {
      usedIds.add(word.id)
      selected.push(word)
    }
    offset++
  }

  // Guaranteed fallback if pool was small
  while (selected.length < 10) {
    selected.push(DAILY_VOCABULARY_POOL[selected.length % total])
  }

  return selected
}
